//! The systemd unit that describes the built-in timer runner. It is written to the admin unit
//! directory when the first timer needs the runner and goes through the normal translation
//! pipeline; the first line marks the file as owned by fake-systemd.
const std = @import("std");
const core = @import("../core/root.zig");
const policy = @import("../backend/policy.zig");

pub const runner_unit = "fake-systemd-timers.service";
pub const owned_line = "# Generated by fake-systemd: removed together with the last built-in timer.";

const system_text = owned_line ++
    \\
    \\[Unit]
    \\Description=fake-systemd timer runner
    \\
    \\[Service]
    \\Type=simple
++ "\nExecStart=" ++ policy.executor_path ++ " --timers\n" ++
    \\Restart=always
    \\
    \\[Install]
    \\WantedBy=multi-user.target
    \\
;

const user_text = owned_line ++
    \\
    \\[Unit]
    \\Description=fake-systemd timer runner
    \\
    \\[Service]
    \\Type=simple
++ "\nExecStart=" ++ policy.executor_path ++ " --timers --user\n" ++
    \\Restart=always
    \\
    \\[Install]
    \\WantedBy=default.target
    \\
;

pub fn unitText(scope: core.Scope) []const u8 {
    return switch (scope) {
        .system => system_text,
        .user => user_text,
    };
}

pub fn isOwned(content: []const u8) bool {
    return std.mem.startsWith(u8, content, owned_line);
}

test "runner unit text" {
    try std.testing.expect(isOwned(unitText(.system)));
    try std.testing.expect(std.mem.find(u8, unitText(.system), "ExecStart=/usr/bin/fake-systemd --timers\n") != null);
    try std.testing.expect(std.mem.find(u8, unitText(.user), "ExecStart=/usr/bin/fake-systemd --timers --user\n") != null);
    try std.testing.expect(!isOwned("[Unit]\n"));
}
